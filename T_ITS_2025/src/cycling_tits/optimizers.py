"""Solvers for the network-upgrade problem (Problem 2 of the paper).

* ``brute_force``  - exact optimum by enumerating all configurations (benchmark only)
* ``run_mlcc``     - the proposed MLCC heuristic
* ``run_sga``      - pygmo standard genetic algorithm, random initial population ("SGA")
                     or seeded with the MLCC solution ("SGA-MLCC")
* ``run_bayesian`` - scikit-optimize ``gp_minimize`` + random repair (as in the paper)

All solvers return a dict with the new DoS ``levels``, the predicted value ``y``,
the % of achievable improvement and the run time.  The objective is the
prediction of ``Model`` (safety or comfort) under the budget ``alpha * B_max``.

Faithfulness notes
------------------
* All solvers share the same objective: untouched edges keep their stored
  weighted length, upgraded edges get length * w(DoS).  (The original GA /
  Bayesian scripts re-weighted every edge, which shifted their baseline by
  ~0.003 with respect to MLCC; this is unified here so all methods are compared
  on exactly the same objective.)
* The original SGA-MLCC initial population was generated by rejection sampling
  (each edge upgraded with probability 0.5, retry until within budget).  That
  never terminates for large networks with small budgets, so feasible random
  individuals are generated directly here: edges are visited in random order and
  upgraded with probability 0.5 only if the upgrade still fits in the budget.
* "SGA" starts from ``pop_size`` random *feasible* individuals and "SGA-MLCC"
  from the same plus the MLCC solution.  A uniform pygmo population is almost
  always entirely infeasible for small budgets and, with the flat 1e10 penalty,
  the GA then never moves (0 %); the 2024 cluster logs show feasible champions
  from the first generation, consistent with a feasible initial population.
* If the GA champion is infeasible (possible with an all-random population and a
  tiny budget) the original network is reported (0 % improvement).
"""
import itertools
import random
import time

import numpy as np

from .data import dos_vector, with_levels
from .mlcc import mlcc


def _evaluate(model, G, levels, reset):
    if all(int(l) == 6 for l in levels):
        return model.y_fully_safe
    return model.predict(with_levels(G, levels, reset=reset))


def _result(model, G, levels, y0, t0, reset, **extra):
    y = _evaluate(model, G, levels, reset)
    out = {"levels": [int(l) for l in levels], "y": y, "y0": y0,
           "percent": model.percent(y, y0), "time_s": time.time() - t0,
           "cost": model.upgrade_cost(G, levels)}
    out.update(extra)
    return out


# --------------------------------------------------------------------------- MLCC
def run_mlcc(model, G, alpha):
    """MLCC with budget alpha * B_max (+1 as in the original scripts)."""
    t0 = time.time()
    budget = alpha * model.max_budget(G) + 1
    levels, log = mlcc(G, budget, model.cost)
    y0 = model.predict(G)
    return _result(model, G, levels, y0, t0, reset="changed", n_upgrades=len(log))


# --------------------------------------------------------------------- brute force
def enumerate_all(model, G, progress=False):
    """Evaluate every configuration once (138,240 for the benchmark).

    Returns ``(configs, costs, values, seconds)``; the optimum for any budget is
    then the best value among configurations whose cost fits (see ``brute_force``).
    """
    t0 = time.time()
    x0 = dos_vector(G)
    ranges = [range(l, 7) for l in x0]
    it = itertools.product(*ranges)
    if progress:
        from tqdm.auto import tqdm
        it = tqdm(it, total=int(np.prod([len(r) for r in ranges])), leave=False)
    configs, costs, values = [], [], []
    for x in it:
        configs.append(x)
        costs.append(model.upgrade_cost(G, x))
        values.append(_evaluate(model, G, x, reset="changed"))
    return np.array(configs), np.array(costs), np.array(values), time.time() - t0


def brute_force(model, G, alpha, table=None):
    """Exact optimum for budget alpha * B_max.

    ``table`` is the output of ``enumerate_all`` (computed once and reused for all
    alphas).  The reported time is the time of a full enumeration.
    """
    t0 = time.time()
    configs, costs, values, t_enum = table if table is not None else enumerate_all(model, G)
    budget = alpha * model.max_budget(G)
    y0 = _evaluate(model, G, dos_vector(G), reset="changed")
    ok = np.where(costs <= budget)[0]
    best = configs[ok[np.argmax(values[ok])]]
    res = _result(model, G, best, y0, t0, reset="changed")
    res["time_s"] = t_enum
    return res


# --------------------------------------------------------------------------- SGA
def _random_feasible(G, x0, budget, model, rng):
    x = list(x0)
    spent = 0.0
    edges = list(G.edges(data=True))
    for i in rng.sample(range(len(x)), len(x)):
        if x[i] < 6 and rng.random() < 0.5:
            new = x[i] + rng.randint(1, 6 - x[i])
            c = edges[i][2]["distance"] * model.cost[x0[i]][new]
            if spent + c <= budget:
                x[i], spent = new, spent + c
    return x


class _UpgradeProblem:
    """pygmo user-defined problem: minimise -(y(x) - y0) s.t. cost(x) <= budget."""

    def __init__(self, model, G, budget, y0):
        self.model, self.G, self.budget, self.y0 = model, G, budget, y0
        self.x0 = dos_vector(G)

    def fitness(self, x):
        if self.model.upgrade_cost(self.G, x) > self.budget:
            return [1e10]
        return [-(_evaluate(self.model, self.G, x, reset="changed") - self.y0)]

    def get_bounds(self):
        return (list(map(float, self.x0)), [6.0] * len(self.x0))

    def get_nix(self):
        return len(self.x0)


def run_sga(model, G, alpha, init="random", generations=80, pop_size=50, seed=0, mlcc_levels=None):
    """pygmo SGA as in the paper (80 generations, population 50).

    init="random": random feasible population ("SGA")
    init="mlcc":   MLCC solution + ``pop_size`` random feasible individuals ("SGA-MLCC")

    Returns the result dict plus ``history``: value / % / cumulative time per generation.
    """
    import pygmo as pg

    t0 = time.time()
    x0 = dos_vector(G)
    budget = alpha * model.max_budget(G)
    y0 = _evaluate(model, G, x0, reset="changed")
    prob = pg.problem(_UpgradeProblem(model, G, budget, y0))
    rng = random.Random(seed)

    pop = pg.population(prob, seed=seed)
    if init == "mlcc":
        if mlcc_levels is None:
            mlcc_levels = run_mlcc(model, G, alpha)["levels"]
        # MLCC runs with budget + 1 (as in the original scripts); make sure the seed is
        # feasible for the GA budget, otherwise it would get the 1e10 penalty.
        if model.upgrade_cost(G, mlcc_levels) > budget:
            mlcc_levels = _repair(mlcc_levels, x0, G, budget, model, random.Random(seed))
        pop.push_back([float(v) for v in mlcc_levels])
    for _ in range(pop_size):
        pop.push_back([float(v) for v in _random_feasible(G, x0, budget, model, rng)])

    algo = pg.algorithm(pg.sga(gen=1, seed=seed))
    hist = {"value": [], "percent": [0.0], "cumtime_s": []}
    elapsed = 0.0
    for _ in range(generations):
        t = time.time()
        pop = algo.evolve(pop)
        elapsed += time.time() - t
        champ = [int(round(v)) for v in pop.champion_x]
        y = y0 if pop.champion_f[0] >= 1e10 else _evaluate(model, G, champ, reset="changed")
        hist["value"].append(y)
        hist["percent"].append(model.percent(y, y0))
        hist["cumtime_s"].append(elapsed)

    champ = [int(round(v)) for v in pop.champion_x]
    if pop.champion_f[0] >= 1e10:
        champ = list(x0)
    return _result(model, G, champ, y0, t0, reset="changed", history=hist)


# ---------------------------------------------------------------------- Bayesian
def _repair(x, x0, G, budget, model, rng):
    """Port of ``adjust_champion_randomly``: remove the sentinel 7, then downgrade
    random edges one level at a time until the budget is met."""
    x = list(x)
    for i, v in enumerate(x):
        if v == 7:
            x[i] = rng.randint(x0[i], 6)
        x[i] = max(x[i], x0[i])
    while model.upgrade_cost(G, x) > budget:
        cand = [i for i in range(len(x)) if x[i] > x0[i]]
        if not cand:
            break
        x[rng.choice(cand)] -= 1
    return x


def run_bayesian(model, G, alpha, n_calls=20, seed=0):
    """Bayesian optimisation (skopt.gp_minimize) as in the original notebooks.

    Each variable is an Integer in [DoS_e, 7]; 7 is a sentinel (skopt needs
    low < high for edges already at DoS 6) penalised like infeasible points.
    The best point is then repaired to satisfy the budget.
    """
    from skopt import gp_minimize
    from skopt.space import Integer

    t0 = time.time()
    x0 = dos_vector(G)
    budget = alpha * model.max_budget(G)
    y0 = _evaluate(model, G, x0, reset="changed")
    space = [Integer(int(v), 7) for v in x0]

    def f(x):
        if 7 in x or model.upgrade_cost(G, x) > budget:
            return 1e10
        return -_evaluate(model, G, x, reset="changed")

    res = gp_minimize(f, space, n_calls=n_calls, random_state=seed)
    x = _repair(res.x, x0, G, budget, model, random.Random(seed))
    return _result(model, G, x, y0, t0, reset="changed")


def evaluate(model, G, levels):
    """Prediction of ``model`` for network ``G`` with DoS ``levels`` (same rules as the solvers)."""
    return _evaluate(model, G, levels, reset="changed")
